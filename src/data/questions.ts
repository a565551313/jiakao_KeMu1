export function pickExam(size = EXAM_SIZE): Question[] {
  const judge = shuffle(QUESTION_BANK.filter((q) => q.type === "judge"));
  const single = shuffle(QUESTION_BANK.filter((q) => q.type === "single"));
  const picked = [
    ...judge.slice(0, JUDGE_COUNT),
    ...single.slice(0, SINGLE_COUNT),
  ];
  const need = size - picked.length;
  if (need > 0) {
    const rest = shuffle(
      QUESTION_BANK.filter((q) => !picked.some((p) => p.id === q.id)),
    );
    picked.push(...rest.slice(0, need));
  }
  return shuffle(picked).slice(0, size);
}

export function examStats(questions: Question[], answers: { selected: AnswerKey | null; judged: boolean }[]) {
  let correct = 0;
  let wrong = 0;
  let blank = 0;
  questions.forEach((q, i) => {
    const a = answers[i];
    if (!a || a.selected === null) {
      blank += 1;
      return;
    }
    if (a.selected === q.answer) correct += 1;
    else wrong += 1;
  });
  return { correct, wrong, blank, score: correct };
}
